const RULES = [
  ['panel', /\b(panel|mozunitor)\b/],
  ['llm', /\b(ollama|llm|gemini|model|gpt|claude|rag|inference|bonsai)\b/],
  ['db', /\b(postgres|mysql|redis|sqlite|mongo|database|db)\b/],
  ['net', /(proxy|clash|tailscale|vpn|tunnel|forward)|\buu\b/],
  ['term', /\b(ssh|sshd|shell|dsh|terminal|cmd)\b/],
  ['web', /\b(web|http|serve|server|sillytavern|hust|site)\b/],
  ['tool', /\b(launcher|maimai|majdata|tempokiri|tool|app)\b/],
];

export function serviceIcon(it) {
  const custom = it && it.icon;
  if (custom && GLYPHS[custom]) return custom;
  // 先认 id/名称，再退到角色说明 —— 角色里常提到别的服务，先看它会张冠李戴
  const head = [it && it.id, it && it.name].filter(Boolean).join(' ').toLowerCase();
  for (const [name, re] of RULES) {
    if (re.test(head)) return name;
  }
  const role = String((it && it.role) || '').toLowerCase();
  for (const [name, re] of RULES) {
    if (re.test(role)) return name;
  }
  return 'generic';
}

const LABELS = {
  panel: '面板', llm: '模型', db: '数据库', net: '网络',
  term: '终端', web: 'Web', tool: '工具', generic: '服务',
};

export function iconLabel(name) {
  return LABELS[name] || LABELS.generic;
}

export function iconSvg(name) {
  const rows = GLYPHS[name] || GLYPHS.generic;
  const parts = [`<svg class="pix" viewBox="0 0 16 16" width="16" height="16" `
    + 'shape-rendering="crispEdges" aria-hidden="true">'];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') { x += 1; continue; }
      const start = x;
      while (x < row.length && row[x] === '#') x += 1;
      parts.push(`<rect x="${start}" y="${y}" width="${x - start}" height="1"/>`);
    }
  });
  parts.push('</svg>');
  return parts.join('');
}
